# OMP event-stream analysis (turn-*.json preferred, sessions/*.jsonl fallback)
# schema learned by inspecting real session store jsonl under ~/.omp/agent/sessions (read-only);
# exact turn-*.json shape from `--mode json` is not directly observed, so this stays defensive:
# any field it cannot find comes back null/None rather than raising.
# --------------------------------------------------------------------------------------

def load_ndjson_or_json(path: Path):
    events, parse_errors = [], 0
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return events, parse_errors
    lines = [l for l in text.splitlines() if l.strip()]
    ok_any = False
    for l in lines:
        try:
            d = json.loads(l)
        except json.JSONDecodeError:
            parse_errors += 1
            continue
        if isinstance(d, dict):
            events.append(d)
            ok_any = True
        elif isinstance(d, list):
            events.extend(x for x in d if isinstance(x, dict))
            ok_any = True
    if not ok_any and text.strip():
        try:
            d = json.loads(text)
            if isinstance(d, list):
                events = [x for x in d if isinstance(x, dict)]
            elif isinstance(d, dict):
                for key in ("events", "messages", "items", "log"):
                    if isinstance(d.get(key), list):
                        events = [x for x in d[key] if isinstance(x, dict)]
                        break
                else:
                    events = [d]
            parse_errors = 0
        except Exception:
            pass
    return events, parse_errors


def walk_dicts(obj, depth=0, maxdepth=14):
    if depth > maxdepth:
        return
    if isinstance(obj, dict):
        yield obj
        for v in obj.values():
            yield from walk_dicts(v, depth + 1, maxdepth)
    elif isinstance(obj, list):
        for v in obj:
            yield from walk_dicts(v, depth + 1, maxdepth)


def is_failure_result(res: dict | None) -> bool | None:
    if res is None:
        return None
    if res.get("isError"):
        return True
    d = res.get("details") or {}
    cells = d.get("cells")
    if isinstance(cells, list):
        for c in cells:
            ec = c.get("exitCode") if isinstance(c, dict) else None
            if isinstance(ec, int) and ec != 0:
                return True
    ec = d.get("exitCode")
    if isinstance(ec, int) and ec != 0:
        return True
    if FAIL_TEXT_RE.search(res.get("text", "") or ""):
        return True
    return False


def analyze_events(run_out: Path, test_cmd: str) -> dict:
    turn_files = sorted(
        run_out.glob("turn-*.json"),
        key=lambda p: int(m.group(1)) if (m := re.search(r"turn-(\d+)", p.name)) else 0,
    )
    all_events, raw_parse_errors = [], 0
    for tf in turn_files:
        evs, errs = load_ndjson_or_json(tf)
        all_events.extend(evs)
        raw_parse_errors += errs
    event_source = "turn-json" if all_events else None

    if not all_events:
        sess_dir = run_out / "sessions"
        sess_files = sorted(sess_dir.rglob("*.jsonl")) if sess_dir.exists() else []
        for sf in sess_files:
            evs, errs = load_ndjson_or_json(sf)
            all_events.extend(evs)
            raw_parse_errors += errs
        if all_events:
            event_source = "session-jsonl"

    if not all_events:
        return {
            "event_source": None, "raw_ndjson_parse_errors": raw_parse_errors,
            "tool_call_counts": None, "tool_call_count_source": None, "test_run_tool_calls": None,
            "reproduced_before_first_edit": None, "harness_parse_errors": None, "total_tool_errors": None,
            "prompt_tokens_sum": None, "completion_tokens_sum": None, "reasoning_tokens_sum": None,
            "cache_read_tokens_sum": None, "cache_write_tokens_sum": None, "assistant_turns": None,
        }

    counts_toolcall, ordered_toolcall = {}, []
    counts_start, ordered_start = {}, []
    usage_list = []
    results_by_id = {}
    error_events = []
    harness_parse_error_count = 0
    idx = 0

    for e in all_events:
        for node in walk_dicts(e):
            if node.get("type") == "toolCall" and isinstance(node.get("name"), str):
                name = node["name"]
                counts_toolcall[name] = counts_toolcall.get(name, 0) + 1
                args = node.get("arguments")
                argtext = ""
                if isinstance(args, dict):
                    argtext = " ".join(str(v) for v in args.values() if isinstance(v, (str, int, float)))
                ordered_toolcall.append({"name": name, "idx": idx, "args_text": argtext, "id": node.get("id")})
                idx += 1
            elif node.get("type") == "custom" and node.get("customType") == "tool_execution_start":
                data = node.get("data") or {}
                tn = data.get("toolName")
                if tn:
                    counts_start[tn] = counts_start.get(tn, 0) + 1
                    a = data.get("args") if isinstance(data.get("args"), dict) else {}
                    argtext = " ".join(str(v) for v in a.values())
                    ordered_start.append(
                        {"name": tn, "idx": idx, "args_text": argtext, "id": data.get("toolCallId")}
                    )
                    idx += 1
            elif node.get("type") == "message" and isinstance(node.get("message"), dict):
                m = node["message"]
                if m.get("role") == "assistant" and isinstance(m.get("usage"), dict):
                    usage_list.append(m["usage"])
                elif m.get("role") == "toolResult":
                    content = m.get("content")
                    text = ""
                    if isinstance(content, list):
                        text = " ".join(c.get("text", "") for c in content if isinstance(c, dict))
                    elif isinstance(content, str):
                        text = content
                    res = {"toolName": m.get("toolName"), "text": text, "isError": bool(m.get("isError")),
                           "details": m.get("details")}
                    tcid = m.get("toolCallId")
                    if tcid:
                        results_by_id[tcid] = res
                    if res["isError"]:
                        error_events.append({"toolName": res["toolName"], "text": text[:300]})
                        if HARNESS_ERR_RE.search(text):
                            harness_parse_error_count += 1

    if sum(counts_toolcall.values()) > 0:
        tool_call_counts, tool_calls_ordered, tc_source = counts_toolcall, ordered_toolcall, "toolCall-blocks"
    else:
        tool_call_counts, tool_calls_ordered, tc_source = counts_start, ordered_start, "tool_execution_start"

    test_run_calls = []
    for tc in tool_calls_ordered:
        if tc["name"].lower() in RUN_TOOL_NAMES:
            at = tc["args_text"] or ""
            if (test_cmd and test_cmd in at) or re.search(r"(?i)vitest|pytest|npm (run )?(test|unit)|node --test", at):
                test_run_calls.append(tc)

    first_edit_idx = None
    for tc in tool_calls_ordered:
        if tc["name"].lower() in ("edit", "write"):
            first_edit_idx = tc["idx"]
            break

    first_failing_run_idx = None
    for tc in tool_calls_ordered:
        if tc["name"].lower() in RUN_TOOL_NAMES and is_failure_result(results_by_id.get(tc["id"])):
            first_failing_run_idx = tc["idx"]
            break

    if first_edit_idx is None:
        reproduced_before_edit = None
    elif first_failing_run_idx is None:
        reproduced_before_edit = False
    else:
        reproduced_before_edit = first_failing_run_idx < first_edit_idx

    def usum(key):
        vals = [u.get(key) for u in usage_list if isinstance(u.get(key), (int, float))]
        return sum(vals) if vals else (0 if usage_list else None)

    reasoning_vals = []
    for u in usage_list:
        for k in ("reasoning", "reasoningTokens", "thinkingTokens", "thinking"):
            v = u.get(k)
            if isinstance(v, (int, float)):
                reasoning_vals.append(v)
                break
    reasoning_sum = sum(reasoning_vals) if reasoning_vals else None

    return {
        "event_source": event_source,
        "raw_ndjson_parse_errors": raw_parse_errors,
        "tool_call_counts": tool_call_counts,
        "tool_call_count_source": tc_source,
        "test_run_tool_calls": len(test_run_calls),
        "reproduced_before_first_edit": reproduced_before_edit,
        "harness_parse_errors": harness_parse_error_count,
        "total_tool_errors": len(error_events),
        "prompt_tokens_sum": usum("input"),
        "completion_tokens_sum": usum("output"),
        "reasoning_tokens_sum": reasoning_sum,
        "cache_read_tokens_sum": usum("cacheRead"),
        "cache_write_tokens_sum": usum("cacheWrite"),
        "assistant_turns": len(usage_list) if usage_list else None,
    }


def wallclock_from_driver_log(run_out: Path):
    f = run_out / "driver.log"
    if not f.exists():
        return None
    times = re.findall(r"^\[(\d\d):(\d\d):(\d\d)\]", f.read_text(encoding="utf-8", errors="replace"), re.M)
    if len(times) < 2:
        return None
    def to_sec(t):
        return int(t[0]) * 3600 + int(t[1]) * 60 + int(t[2])
    secs = [to_sec(t) for t in times]
    delta = secs[-1] - secs[0]
    if delta < 0:
        delta += 24 * 3600  # best-effort midnight rollover; driver.log has no date component
    return delta


