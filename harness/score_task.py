def score_task(task: str, label: str, p1_timeout=300, p2_timeout=900, p3_timeout=300) -> dict:
    turns = load_turns(task)
    base_repo = base_repo_dir(turns)
    wt = worktree_dir(task, label)
    run_out = run_out_dir(task, label)
    run_out.mkdir(parents=True, exist_ok=True)

    result = {"task": task, "label": label, "worktree": str(wt), "run_dir": str(run_out)}
    warnings = []
    if not wt.exists():
        warnings.append(f"worktree not found: {wt}")
    if not (run_out / "final.diff").exists():
        warnings.append("final.diff missing in run dir")
    if warnings:
        result["warnings"] = warnings

    if wt.exists():
        p1 = run_p1(task, wt, base_repo, run_out, p1_timeout)
        p2 = run_p2(wt, turns, p2_timeout)
        p3 = run_p3(task, wt, base_repo, run_out, label, p3_timeout)
    else:
        p1 = p2 = p3 = {"status": "ERROR", "reason": "no worktree"}

    secondary = secondary_metrics(task, run_out)
    events = analyze_events(run_out, turns.get("test_cmd", ""))
    wallclock = wallclock_from_driver_log(run_out)

    overall_pass = all(x.get("status") == "PASS" for x in (p1, p2, p3))
    result.update({
        "overall_pass": overall_pass,
        "P1": p1, "P2": p2, "P3": p3,
        "secondary": secondary,
        "events": events,
        "wallclock_seconds": wallclock,
    })
    (run_out / "score.json").write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")
    return result


def one_line_summary(r: dict) -> str:
    ov = "PASS" if r["overall_pass"] else "FAIL"
    sec = r["secondary"]
    ev = r["events"]
    tool_total = sum(ev["tool_call_counts"].values()) if ev.get("tool_call_counts") else None
    return (
        f"{r['task']}/{r['label']}: {ov}  (P1={r['P1']['status']} P2={r['P2']['status']} P3={r['P3']['status']})  "
        f"loc +{sec['loc_added']}/-{sec['loc_removed']} files={sec['files_touched_count']} "
        f"tools={tool_total} wall={r['wallclock_seconds']}s"
    )


def write_scoreboard(results: list[dict]):
    tasks_present = [t for t in TASKS if any(r["task"] == t for r in results)]
    labels_present = sorted(set(r["label"] for r in results))
    index = {(r["task"], r["label"]): r for r in results}

    lines = ["# Scoreboard", "", "| task | " + " | ".join(labels_present) + " |",
              "|---|" + "---|" * len(labels_present)]
    for t in tasks_present:
        row = [t]
        for l in labels_present:
            r = index.get((t, l))
            if not r:
                row.append("")
                continue
            ov = "PASS" if r["overall_pass"] else "FAIL"
            sec = r["secondary"]
            ev = r["events"]
            tool_total = sum(ev["tool_call_counts"].values()) if ev.get("tool_call_counts") else "n/a"
            cell = (
                f"**{ov}**<br>P1={r['P1']['status']} P2={r['P2']['status']} P3={r['P3']['status']}<br>"
                f"<sub>loc +{sec['loc_added']}/-{sec['loc_removed']}, files={sec['files_touched_count']}, "
                f"tools={tool_total}, test-runs={ev.get('test_run_tool_calls')}, "
                f"repro-first={ev.get('reproduced_before_first_edit')}, wall={r['wallclock_seconds']}s</sub>"
            )
            row.append(cell)
        lines.append("| " + " | ".join(row) + " |")
    RUNS.mkdir(parents=True, exist_ok=True)
    (RUNS / "scoreboard.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("task", nargs="?", choices=TASKS)
    ap.add_argument("label", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--p1-timeout", type=int, default=300)
    ap.add_argument("--p2-timeout", type=int, default=900)
    ap.add_argument("--p3-timeout", type=int, default=300)
    args = ap.parse_args()

    if args.all:
        results = []
        for task in TASKS:
            d = RUNS / task
            if not d.exists():
                continue
            for label_dir in sorted(p for p in d.iterdir() if p.is_dir()):
                if not (label_dir / "final.diff").exists():
                    continue
                r = score_task(task, label_dir.name, args.p1_timeout, args.p2_timeout, args.p3_timeout)
                print(one_line_summary(r))
                results.append(r)
        if results:
            write_scoreboard(results)
            print(f"wrote {RUNS / 'scoreboard.md'}")
        else:
            print("no run dirs with final.diff found under " + str(RUNS))
        return

    if not args.task or not args.label:
        ap.error("task and label are required unless --all")
    r = score_task(args.task, args.label, args.p1_timeout, args.p2_timeout, args.p3_timeout)
    print(one_line_summary(r))


if __name__ == "__main__":
    main()
