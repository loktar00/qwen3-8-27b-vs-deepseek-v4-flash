#!/usr/bin/env python3
"""score_task.py -- automated scorer for the DSV4 vs Qwen3.8 A/B (see ab/SCORING.md).

usage:
  python score_task.py <task> <label>     score one run, write _runs/<task>/<label>/score.json
  python score_task.py --all              score every run dir present, also write _runs/scoreboard.md

<task> in {radix, anyio, hatetris, chessground, chessground-322, chessjs}
<label> matches the worktree/run-dir naming from run_omp_task.sh (e.g. "dsv4", "qwen", "qwen-med").

Layout assumed (see run_omp_task.sh):
  D:/dev/ab-tasks/_briefs/<task>/turns.json   -- {"repo"/"dir", "test_cmd", "install", "turns":[...]}
  D:/dev/ab-tasks/_hidden/<task>/fix-pr-*.diff, issue-*.json, repro-*.test.ts
  D:/dev/ab-tasks/<task>-<label>/             -- model's worktree (final state, uncommitted diff on disk)
  D:/dev/ab-tasks/_runs/<task>/<label>/       -- final.diff, turn-*.json, driver.log, sessions/, final-tests.log,
                                                  base-sha.txt

P1/P2/P3 are defined in ab/SCORING.md section 2A/2B. This script is deliberately conservative about mutating
anything outside of a run's own scratch scaffolding: the model's worktree is only ever touched via an
apply-run-restore cycle (P1) that puts back exactly what was there before, and P3's "does the model's own test
fail on the base commit" check happens in a disposable `git worktree` next to the base clone, never in the base
clone itself.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path("D:/dev/ab-tasks")
RUNS = ROOT / "_runs"
BRIEFS = ROOT / "_briefs"
HIDDEN = ROOT / "_hidden"

TASKS = ["radix", "anyio", "hatetris", "chessground", "chessground-322", "chessjs"]

# final.diff / upstream diffs both come from `git diff`; these are lockfile/build noise excluded from
# final.diff by run_omp_task.sh itself (':!package-lock.json' ':!pnpm-lock.yaml') -- apply the same exclusion
# to upstream diffs so LOC/precision comparisons are apples-to-apples.
EXCLUDE_BASENAMES = {"package-lock.json", "pnpm-lock.yaml", "yarn.lock"}

TEST_PATH_RE = re.compile(r"(?i)(^|[\\/])(__tests__|tests?|spec)([\\/]|$)|\.(test|spec)\.")

RUN_TOOL_NAMES = {"bash", "eval", "command", "shell", "exec", "execute", "run", "terminal", "cmd"}

# gitignored files that are generated by a task's install/build step and are required just to
# import the source under test, so a bare `git worktree add` (used for P3's scratch worktree,
# which never runs install) won't have them. Copied in (not junctioned -- small, generated,
# deterministic from tracked sources) alongside the node_modules/.venv junction. Discovered via
# chessjs: src/pgn.js + src/pgn.d.ts come from the peggy parser build step (`npm run parser`,
# part of `prepare`/`build`), are in .gitignore, and chess.ts fails to import without them.
EXTRA_GENERATED_FILES = {
    "chessjs": ["src/pgn.js", "src/pgn.d.ts"],
}

# live-bug tasks (SCORING.md 2B): P1 is a frozen, pre-written repro test from _hidden/, not an
# upstream fix diff. hidden_dir is where the frozen test file actually lives under _hidden/ --
# NOT necessarily the task name: chessground-322 reuses the chessground #386 task's worktree
# lineage (base repo D:/dev/ab-tasks/chessground, distinct from chessground-ref which the
# existing "chessground"/#386 task uses) but its hidden material sits under _hidden/chessground/
# alongside #386's, keyed by issue number in the filename.
FROZEN_REPRO = {
    "chessground": {"hidden_dir": "chessground", "file": "repro-386.test.ts", "dest_dir": "tests"},
    "chessground-322": {"hidden_dir": "chessground", "file": "repro-322.test.ts", "dest_dir": "tests"},
    "chessjs": {"hidden_dir": "chessjs", "file": "repro-577.test.ts", "dest_dir": "__tests__"},
}

HARNESS_ERR_RE = re.compile(
    r"(?i)(validation failed for tool|invalid json|failed to pars|malformed|unexpected token"
    r"|parse error|schema mismatch|unknown tool|no such tool)"
)
FAIL_TEXT_RE = re.compile(r"(?i)\b(fail(?:ed|ure)?|error|exception|traceback|assertionerror)\b")


